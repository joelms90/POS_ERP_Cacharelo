class LocalBranchRequisition {
  final String id; // UUID v4 generated by the client
  final String fromBranchId;
  final String toWarehouseId;
  final String status; // 'pending_approval'
  final String? notes;
  final DateTime createdAt;
  final String syncState; // 'pending', 'synced', 'failed'
  final List<LocalBranchRequisitionItem> items;
  final int itemCount;

  LocalBranchRequisition({
    required this.id,
    required this.fromBranchId,
    required this.toWarehouseId,
    required this.status,
    this.notes,
    required this.createdAt,
    required this.syncState,
    required this.items,
    int? itemCount,
  }) : itemCount = itemCount ?? items.length;

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'fromBranchId': fromBranchId,
      'toWarehouseId': toWarehouseId,
      'status': status,
      'notes': notes,
      'createdAt': createdAt.toIso8601String(),
      'syncState': syncState,
      'items': items.map((i) => i.toMap()).toList(),
      'itemCount': itemCount,
    };
  }

  factory LocalBranchRequisition.fromMap(Map<String, dynamic> map) {
    final rawItems = map['items'];
    final items = rawItems is List
        ? rawItems
            .map((i) => LocalBranchRequisitionItem.fromMap(
                  Map<String, dynamic>.from(i as Map),
                ))
            .toList()
        : <LocalBranchRequisitionItem>[];

    return LocalBranchRequisition(
      id: map['id'],
      fromBranchId: map['fromBranchId'],
      toWarehouseId: map['toWarehouseId'],
      status: map['status'],
      notes: map['notes'],
      createdAt: DateTime.parse(map['createdAt']),
      syncState: map['syncState'],
      items: items,
      itemCount: (map['itemCount'] as num?)?.toInt() ?? items.length,
    );
  }
}

class LocalBranchRequisitionItem {
  final String id;
  final String requisitionId;
  final String productId;
  final double quantityRequested;

  LocalBranchRequisitionItem({
    required this.id,
    required this.requisitionId,
    required this.productId,
    required this.quantityRequested,
  });

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'requisitionId': requisitionId,
      'productId': productId,
      'quantityRequested': quantityRequested,
    };
  }

  factory LocalBranchRequisitionItem.fromMap(Map<String, dynamic> map) {
    return LocalBranchRequisitionItem(
      id: map['id'],
      requisitionId: map['requisitionId'],
      productId: map['productId'],
      quantityRequested: (map['quantityRequested'] as num).toDouble(),
    );
  }
}
